import copy
import numpy as np
import pandas as pd
from .solver import solve_case
from .diagnostics import key_curves, case_metrics, energy_balance, monotonic_alpha_check


def _mid_arrays(result):
    k=key_curves(result)
    m=k[k.position=='part_mid'].sort_values('t_s')
    return m.t_s.to_numpy(),m.T_FE_C.to_numpy(),m.alpha_FE.to_numpy()


def mesh_convergence(case,config):
    levels=list(config['verification']['mesh_levels'])
    runs=[]
    for n in levels:
        r=solve_case(case,config,{'n_tool_elements':int(n),'n_part_elements':int(n)})
        met=case_metrics(r); t,T,a=_mid_arrays(r)
        runs.append((n,r,met,t,T,a))
    tf,Tf,af=runs[-1][3],runs[-1][4],runs[-1][5]
    rows=[]
    for n,r,met,t,T,a in runs:
        Tr=np.interp(tf,t,T); ar=np.interp(tf,t,a)
        rows.append({
            'n_elements_each_layer':n,
            'part_mid_Tmax_C':met['part_mid_Tmax_C'],
            'part_mid_final_alpha':met['part_mid_final_alpha'],
            'max_abs_T_difference_to_finest_C':float(np.max(np.abs(Tr-Tf))),
            'max_abs_alpha_difference_to_finest':float(np.max(np.abs(ar-af))),
        })
    return pd.DataFrame(rows)


def time_convergence(case,config):
    steps=list(config['verification']['time_max_steps_s'])
    runs=[]
    for s in steps:
        r=solve_case(case,config,{'max_step_s':float(s),'output_dt_s':min(float(s),20.0)})
        met=case_metrics(r); t,T,a=_mid_arrays(r)
        runs.append((s,r,met,t,T,a))
    tf,Tf,af=runs[-1][3],runs[-1][4],runs[-1][5]
    rows=[]
    for s,r,met,t,T,a in runs:
        Tr=np.interp(tf,t,T); ar=np.interp(tf,t,a)
        rows.append({
            'max_step_s':s,'part_mid_Tmax_C':met['part_mid_Tmax_C'],
            'part_mid_final_alpha':met['part_mid_final_alpha'],
            'max_abs_T_difference_to_finest_C':float(np.max(np.abs(Tr-Tf))),
            'max_abs_alpha_difference_to_finest':float(np.max(np.abs(ar-af))),
        })
    return pd.DataFrame(rows)


def run_verification(case,config):
    case=dict(case)
    main=solve_case(case,config)
    metrics=case_metrics(main)
    alpha_ok,min_da,amin,amax=monotonic_alpha_check(main)
    eb=energy_balance(main)
    mesh=mesh_convergence(case,config)
    time=time_convergence(case,config)

    v=config['verification']
    mesh_peak_change=abs(mesh.part_mid_Tmax_C.iloc[-1]-mesh.part_mid_Tmax_C.iloc[-2])
    time_peak_change=abs(time.part_mid_Tmax_C.iloc[-1]-time.part_mid_Tmax_C.iloc[-2])
    energy_max=float(eb.normalized_energy_residual.abs().max())
    cycle_end=main.cycle.temperature_C(main.cycle.total_process_time_s)

    # Paired control: same FE problem with reaction heat disabled. This proves
    # that the observed overshoot is generated by b*dalpha/dt, not by the cure cycle.
    no_heat_cfg=copy.deepcopy(config)
    no_heat_cfg['heat_generation']['physical_b_K']=0.0
    no_heat=solve_case(case,no_heat_cfg)
    no_heat_metrics=case_metrics(no_heat)
    reaction_peak_increment=(metrics['part_mid_Tmax_C']-no_heat_metrics['part_mid_Tmax_C'])

    checks={
      'complete_cooling_cycle':abs(cycle_end-main.cycle.final_temperature_C)<1e-9,
      'alpha_monotonic_and_bounded':alpha_ok and amin>=-1e-10 and amax<=1+1e-10,
      'mesh_peak_converged':mesh_peak_change<=float(v['mesh_peak_temperature_tolerance_C']),
      'time_peak_converged':time_peak_change<=float(v['time_peak_temperature_tolerance_C']),
      'energy_balance':energy_max<=float(v['energy_relative_tolerance']),
      'positive_reaction_exotherm':metrics['part_mid_reaction_exotherm_C']>=float(v['minimum_exotherm_C']),
      'reaction_heat_increases_peak':reaction_peak_increment>=float(v['minimum_reaction_peak_increment_C']),
    }
    summary=pd.DataFrame([{
      'case_id':case['case_id'],**checks,'all_checks_pass':all(checks.values()),
      'mesh_last_peak_change_C':mesh_peak_change,'time_last_peak_change_C':time_peak_change,
      'max_normalized_energy_residual':energy_max,'min_alpha_increment':min_da,
      'no_heat_part_mid_Tmax_C':no_heat_metrics['part_mid_Tmax_C'],
      'reaction_peak_increment_C':reaction_peak_increment,
      **metrics,
    }])
    return main,mesh,time,eb,summary
